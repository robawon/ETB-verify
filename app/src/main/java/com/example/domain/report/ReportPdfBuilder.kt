package com.example.domain.report

import android.content.Context
import android.content.Intent
import android.graphics.Canvas
import android.graphics.Color
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import android.os.Build
import android.text.Layout
import android.text.StaticLayout
import android.text.TextPaint
import androidx.core.content.FileProvider
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

/**
 * Data class containing report information required to generate the PDF document.
 */
data class ReportData(
    val denomination: Int,
    val serialNumber: String,
    val locationText: String,
    val notes: String,
    val isAnonymous: Boolean,
    val aiVerdictCounterfeit: Boolean?,
    val aiConfidence: Float?,
    val timestamp: Long,
    val isAmharic: Boolean
)

/**
 * Builds an A4 PDF report document from the provided ReportData and saves it to cache directory.
 */
fun buildReportPdf(context: Context, data: ReportData): File {
    val reportsDir = File(context.cacheDir, "reports")
    if (!reportsDir.exists()) {
        reportsDir.mkdirs()
    }

    val timeStr = SimpleDateFormat("yyyyMMdd-HHmmss", Locale.US).format(Date(data.timestamp))
    val file = File(reportsDir, "ETB-Report-$timeStr.pdf")

    val pageWidth = 595
    val pageHeight = 842
    val margin = 40f
    val printableWidth = pageWidth - (margin * 2).toInt()
    val footerReservedHeight = 55f
    val maxContentY = pageHeight - margin - footerReservedHeight

    val textPaint = TextPaint().apply {
        isAntiAlias = true
        textSize = 11f
        color = Color.BLACK
        typeface = Typeface.DEFAULT
    }

    val titlePaint = TextPaint().apply {
        isAntiAlias = true
        textSize = 18f
        color = Color.WHITE
        typeface = Typeface.DEFAULT_BOLD
    }

    val subtitlePaint = TextPaint().apply {
        isAntiAlias = true
        textSize = 11f
        color = Color.WHITE
        typeface = Typeface.DEFAULT
    }

    val headingPaint = TextPaint().apply {
        isAntiAlias = true
        textSize = 13f
        color = Color.parseColor("#004D1A")
        typeface = Typeface.DEFAULT_BOLD
    }

    val footerPaint = TextPaint().apply {
        isAntiAlias = true
        textSize = 9f
        color = Color.GRAY
        typeface = Typeface.DEFAULT
    }

    val titleText = if (data.isAmharic) "የሐሰት ብር ሪፖርት" else "Counterfeit Note Report"
    val subAppText = "CounterWatch"
    val reportId = "CW-" + SimpleDateFormat("yyyyMMddHHmm", Locale.US).format(Date(data.timestamp))
    val dateTimeFormatted = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.US).format(Date(data.timestamp))

    val denomStr = "${data.denomination} ETB"
    val serialStr = data.serialNumber.ifBlank { "Not detected" }
    val locationStr = data.locationText.ifBlank { "N/A" }
    val reporterStr = if (data.isAnonymous) (if (data.isAmharic) "ማንነቱ ያልታወቀ" else "Anonymous") else (if (data.isAmharic) "የታወቀ" else "Not anonymous")

    val footerMessage = if (data.isAmharic) {
        "በካውንተርዎች (CounterWatch) አርቴፊሻል ኢንተለጀንስ የተረጋገጠ። ይህ የክትትል ውጤት እንጂ የፎረንሲክ ማረጋገጫ አይደለም። እባክዎ ከኢትዮጵያ ብሔራዊ ባንክ ወይም ከፖሊስ ጋር ያረጋግጡ።"
    } else {
        "Generated by CounterWatch AI screening. This is a screening result, not a forensic confirmation. Please verify with the National Bank of Ethiopia or the police."
    }

    val notesPaint = TextPaint(textPaint).apply { textSize = 11f }
    val notesLayout = if (data.notes.isNotBlank()) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            StaticLayout.Builder.obtain(data.notes, 0, data.notes.length, notesPaint, printableWidth)
                .setAlignment(Layout.Alignment.ALIGN_NORMAL)
                .setLineSpacing(0f, 1f)
                .setIncludePad(false)
                .build()
        } else {
            @Suppress("DEPRECATION")
            StaticLayout(data.notes, notesPaint, printableWidth, Layout.Alignment.ALIGN_NORMAL, 1f, 0f, false)
        }
    } else null

    data class Block(val draw: (Canvas, Float) -> Float, val height: Float)
    val blocks = mutableListOf<Block>()

    // Block: Header + Metadata
    blocks.add(Block({ canvas, y ->
        val paint = Paint().apply { color = Color.parseColor("#004D1A") }
        canvas.drawRect(margin, y, pageWidth - margin, y + 65f, paint)
        canvas.drawText(titleText, margin + 12f, y + 28f, titlePaint)
        canvas.drawText(subAppText, margin + 12f, y + 48f, subtitlePaint)
        var cy = y + 80f
        textPaint.typeface = Typeface.DEFAULT_BOLD
        canvas.drawText("Report ID: $reportId", margin, cy, textPaint)
        cy += 18f
        textPaint.typeface = Typeface.DEFAULT
        canvas.drawText("Date & Time: $dateTimeFormatted", margin, cy, textPaint)
        cy + 28f - y
    }, 130f))

    // Block: Details Heading & Rows
    blocks.add(Block({ canvas, y ->
        var cy = y
        canvas.drawText(if (data.isAmharic) "የዝርዝር መረጃ" else "Report Details", margin, cy, headingPaint)
        cy += 18f
        fun drawRowInline(label: String, value: String) {
            textPaint.typeface = Typeface.DEFAULT_BOLD
            canvas.drawText(label, margin, cy, textPaint)
            textPaint.typeface = Typeface.DEFAULT
            canvas.drawText(value, margin + 130f, cy, textPaint)
            cy += 20f
        }
        drawRowInline(if (data.isAmharic) "የገንዘብ መጠን:" else "Denomination:", denomStr)
        drawRowInline(if (data.isAmharic) "መለያ ቁጥር:" else "Serial Number:", serialStr)
        drawRowInline(if (data.isAmharic) "ቦታ:" else "Location:", locationStr)
        drawRowInline(if (data.isAmharic) "አቅራቢ:" else "Reporter:", reporterStr)
        cy + 10f - y
    }, 110f))

    // Block: AI Screening Result Section
    if (data.aiVerdictCounterfeit != null) {
        blocks.add(Block({ canvas, y ->
            var cy = y
            canvas.drawText(if (data.isAmharic) "የ AI ምርመራ ውጤት" else "AI Screening Result", margin, cy, headingPaint)
            cy += 18f
            val verdictLabel = if (data.aiVerdictCounterfeit) {
                if (data.isAmharic) "እንደ ሐሰተኛ ተለይቷል" else "Flagged as counterfeit"
            } else {
                if (data.isAmharic) "ትክክለኛ ይመስላል" else "Appeared genuine"
            }
            val confVal = data.aiConfidence?.let { "${(it * 100).toInt()}%" } ?: "N/A"
            val confLabel = if (data.isAmharic) "የእርግጠኛ መጠን: $confVal" else "Model confidence: $confVal"

            fun drawRowInline(label: String, value: String) {
                textPaint.typeface = Typeface.DEFAULT_BOLD
                canvas.drawText(label, margin, cy, textPaint)
                textPaint.typeface = Typeface.DEFAULT
                canvas.drawText(value, margin + 130f, cy, textPaint)
                cy += 20f
            }
            drawRowInline(if (data.isAmharic) "ውጤት:" else "Verdict:", verdictLabel)
            drawRowInline(if (data.isAmharic) "እርግጠኛነት:" else "Confidence:", confLabel)
            cy + 10f - y
        }, 70f))
    }

    // Block: Notes Section
    if (notesLayout != null) {
        blocks.add(Block({ canvas, y ->
            var cy = y
            canvas.drawText(if (data.isAmharic) "ማስታወሻዎች" else "Notes", margin, cy, headingPaint)
            cy += 18f
            canvas.save()
            canvas.translate(margin, cy)
            notesLayout.draw(canvas)
            canvas.restore()
            cy + notesLayout.height + 20f - y
        }, 28f + notesLayout.height.toFloat()))
    }

    data class PageAssignment(val blockIndex: Int, val startY: Float)
    val pageAssignments = mutableListOf<MutableList<Block>>()
    var currentPageBlocks = mutableListOf<Block>()
    var currentY = margin

    for (block in blocks) {
        if (currentY + block.height > maxContentY && currentPageBlocks.isNotEmpty()) {
            pageAssignments.add(currentPageBlocks)
            currentPageBlocks = mutableListOf()
            currentY = margin
        }
        currentPageBlocks.add(block)
        currentY += block.height
    }
    if (currentPageBlocks.isNotEmpty()) {
        pageAssignments.add(currentPageBlocks)
    }

    val totalPages = pageAssignments.size.coerceAtLeast(1)

    val pdfDocument = PdfDocument()
    for ((pageIdx, blocksOnPage) in pageAssignments.withIndex()) {
        val pageInfo = PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageIdx + 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        var y = margin
        for (block in blocksOnPage) {
            val usedHeight = block.draw(canvas, y)
            y += usedHeight
        }

        // Draw Footer
        val footerY = pageHeight - 30f
        val footerLayout = if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.M) {
            StaticLayout.Builder.obtain(footerMessage, 0, footerMessage.length, footerPaint, printableWidth)
                .setAlignment(Layout.Alignment.ALIGN_NORMAL)
                .setLineSpacing(0f, 1f)
                .setIncludePad(false)
                .build()
        } else {
            @Suppress("DEPRECATION")
            StaticLayout(footerMessage, footerPaint, printableWidth, Layout.Alignment.ALIGN_NORMAL, 1f, 0f, false)
        }
        canvas.save()
        canvas.translate(margin, footerY - footerLayout.height)
        footerLayout.draw(canvas)
        canvas.restore()

        val pageNumberText = "Page ${pageIdx + 1} of $totalPages"
        canvas.drawText(pageNumberText, pageWidth - margin - footerPaint.measureText(pageNumberText), footerY + 12f, footerPaint)

        pdfDocument.finishPage(page)
    }

    val outputStream = FileOutputStream(file)
    pdfDocument.writeTo(outputStream)
    pdfDocument.close()
    outputStream.close()

    return file
}

/**
 * Opens the Android system share sheet to share the generated PDF report file.
 */
fun shareReportPdf(context: Context, file: File) {
    try {
        val uri = FileProvider.getUriForFile(
            context,
            context.packageName + ".fileprovider",
            file
        )
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "application/pdf"
            putExtra(Intent.EXTRA_STREAM, uri)
            addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
        }
        val chooser = Intent.createChooser(intent, "Share Counterfeit Report")
        if (context !is android.app.Activity) {
            chooser.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        }
        context.startActivity(chooser)
    } catch (e: Exception) {
        android.util.Log.e("ReportPdfBuilder", "Error sharing PDF report", e)
    }
}
